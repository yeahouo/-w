/**
 * @file oled.c
 * @brief SSD1306 128x64 OLED 驱动实现 — 4 线软件 SPI (CS 接 GND)
 *
 * 引脚 (PINCM 已查 TI SysConfig deviceData MSPM0G350X.json 核实):
 *   SCL (D0) = PA28 = IOMUX_PINCM3
 *   SDA (D1) = PA31 = IOMUX_PINCM6
 *   RES      = PB14 = IOMUX_PINCM31
 *   DC       = PB15 = IOMUX_PINCM32
 *
 * 时序: CLK 空闲低, 上升沿采样 (SSD1306 SPI 模式 0 兼容)
 *       DC=0 发命令, DC=1 发数据; CS 接 GND 永久片选
 */

