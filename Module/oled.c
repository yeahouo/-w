/* ============================================================
 *  引脚定义
 * ============================================================ */
#define OLED_SCL_PORT   GPIOA
#define OLED_SCL_PIN    DL_GPIO_PIN_28
#define OLED_SCL_PINCM  IOMUX_PINCM3

#define OLED_SDA_PORT   GPIOA
#define OLED_SDA_PIN    DL_GPIO_PIN_31
#define OLED_SDA_PINCM  IOMUX_PINCM6

#define OLED_RES_PORT   GPIOB
#define OLED_RES_PIN    DL_GPIO_PIN_14
#define OLED_RES_PINCM  IOMUX_PINCM31

#define OLED_DC_PORT    GPIOB
#define OLED_DC_PIN     DL_GPIO_PIN_15
#define OLED_DC_PINCM   IOMUX_PINCM32

/* ============================================================
 *  ms 级延时 — 复用 main.c 的 SysTick 毫秒时钟
 *  必须在 SysTick_Config() 之后调用
 * ============================================================ */
extern volatile uint32_t g_system_ms;

static void oled_delay_ms(uint32_t ms)
{
    uint32_t start = g_system_ms;
    while (g_system_ms - start < ms) { __NOP(); }
}

/* SPI 位时序延时 (~几 us @ 80MHz, SSD1306 SPI 时钟上限 4MHz, 软件远低于此) */
static inline void oled_spi_delay(void)
{
    for (volatile int i = 0; i < 10; ++i) { __NOP(); }
}

